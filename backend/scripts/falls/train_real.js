/**
 * Train the earlier mixed real-activity/simulated-fall experiment.
 * The source activity recordings and prepared feature CSV are not bundled.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCsv, trainFromRows } from './train.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const DATA_CSV = path.resolve(
  process.env.REAL_FALL_FEATURE_CSV || path.join(ROOT, 'data/falls/real/dataset.csv'),
);
const MODEL_PATH = path.resolve(
  process.env.REAL_FALL_MODEL_OUTPUT || path.join(ROOT, 'src/services/fallDetection/model-real.json'),
);
const REPORT_PATH = path.resolve(ROOT, '../docs/phase3/03-real-training-report.md');

function pct(value) {
  return `${(value * 100).toFixed(2)}%`;
}

function main() {
  if (!fs.existsSync(DATA_CSV)) {
    throw new Error(
      `Prepared real-experiment feature CSV not found: ${DATA_CSV}. ` +
        'Provide REAL_FALL_FEATURE_CSV with a 15-column CSV (label plus fourteen features).',
    );
  }

  const source = fs.readFileSync(DATA_CSV, 'utf8');
  if (source.includes('# SYNTHETIC')) {
    throw new Error(`Refusing a synthetic-only CSV for the real-activity experiment: ${DATA_CSV}`);
  }
  const rows = parseCsv(source);
  if (rows.length === 0) throw new Error(`No valid labeled feature rows found in ${DATA_CSV}`);

  const model = trainFromRows(rows);
  model.datasetKind = 'real-activity-with-simulated-falls';
  fs.mkdirSync(path.dirname(MODEL_PATH), { recursive: true });
  fs.writeFileSync(MODEL_PATH, JSON.stringify(model), 'utf8');

  const report = `# Training report: real activity and simulated falls

Generated by \`npm run train:fall:real\` from \`${path.relative(ROOT, DATA_CSV).replaceAll('\\', '/')}\`.

## Source limits

The raw UCI activity recordings and the prepared feature CSV are not included in the source
package. The positive fall class in this earlier experiment is simulated; this experiment
must not be described as training on observed human falls. Set \`REAL_FALL_FEATURE_CSV\` to
a 15-column CSV (label plus fourteen features) to reproduce the reported workflow.

## Five-fold validation

- Feature rows: ${rows.length}
- KNN (k=${model.knn.k}): accuracy ${pct(model.cv.knn.accuracy)}, precision ${pct(model.cv.knn.precision)}, recall ${pct(model.cv.knn.recall)}, F1 ${pct(model.cv.knn.f1)}
- Linear SVM: accuracy ${pct(model.cv.svm.accuracy)}, precision ${pct(model.cv.svm.precision)}, recall ${pct(model.cv.svm.recall)}, F1 ${pct(model.cv.svm.f1)}
- Model written to: \`${path.relative(ROOT, MODEL_PATH).replaceAll('\\', '/')}\`
- Trained at: ${model.trainedAt}
`;
  fs.mkdirSync(path.dirname(REPORT_PATH), { recursive: true });
  fs.writeFileSync(REPORT_PATH, report, 'utf8');
  process.stdout.write(`Trained mixed experiment model from ${rows.length} rows.\n`);
}

try {
  main();
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
}
