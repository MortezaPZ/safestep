/**
 * Train the deployed fall model from SisFall feature rows.
 * Raw SisFall files are intentionally not bundled with the source delivery;
 * put them under data/falls/raw/SisFall or provide a grouped feature CSV.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { convertIfPresent } from './convert_sisfall.js';
import { parseCsv, trainFromRows } from './train.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const RAW = path.join(ROOT, 'data/falls/raw/SisFall');
const PREPARED_CSV = Boolean(process.env.SISFALL_FEATURE_CSV);
const DATA_CSV = path.resolve(process.env.SISFALL_FEATURE_CSV || path.join(ROOT, 'data/falls/dataset.csv'));
const MODEL_PATH = path.join(ROOT, 'src/services/fallDetection/model.json');
const REPORT_PATH = path.resolve(ROOT, '../docs/phase3/04-sisfall-training-report.md');
const SWEEP_PATH = path.resolve(ROOT, '../docs/evaluation/fall-rule-threshold-sweep.csv');

function pct(value) {
  return `${(value * 100).toFixed(2)}%`;
}

function csv(rows) {
  const header = [
    'margin_threshold', 'agree_ratio_threshold', 'sensitivity', 'false_positive_rate',
    'precision', 'accuracy', 'f1', 'tp', 'fp', 'fn', 'tn', 'source',
  ];
  return [
    header.join(','),
    ...rows.map((row) => [
      row.marginThreshold,
      row.agreeThreshold,
      row.sensitivity.toFixed(4),
      row.falsePositiveRate.toFixed(4),
      row.precision.toFixed(4),
      row.accuracy.toFixed(4),
      row.f1.toFixed(4),
      row.tp, row.fp, row.fn, row.tn, row.source,
    ].join(',')),
  ].join('\n') + '\n';
}

function writeReport(model, rowCount) {
  const knn = model.cv.knn;
  const svm = model.cv.svm;
  const report = `# SisFall training report

This report is generated by \`npm run train:fall:sisfall\` from the SisFall feature CSV.

## Source availability

The raw SisFall recordings are not included in this source package. Supply them under
\`backend/data/falls/raw/SisFall\`, or point \`SISFALL_FEATURE_CSV\` at a prepared
17-column CSV (subject_id, recording_id, label, and fourteen features). The checked-in model is retained until
this script completes successfully.

## Training and validation

- Feature rows: ${rowCount}
- Dataset label: \`${model.datasetKind}\`
- KNN: k=${model.knn.k}; five-fold accuracy ${pct(knn.accuracy)}, precision ${pct(knn.precision)}, recall ${pct(knn.recall)}, F1 ${pct(knn.f1)}
- Linear SVM: five-fold accuracy ${pct(svm.accuracy)}, precision ${pct(svm.precision)}, recall ${pct(svm.recall)}, F1 ${pct(svm.f1)}
- Ensemble: five-fold accuracy ${pct(model.cv.ensemble.accuracy)}, precision ${pct(model.cv.ensemble.precision)}, recall ${pct(model.cv.ensemble.recall)}, F1 ${pct(model.cv.ensemble.f1)}
- Trained at: ${model.trainedAt}

The model uses ${model.training.foldStrategy}. Feature scaling is fitted inside each
training fold and hyperparameters are selected in inner folds. The threshold sweep is
written to \`docs/evaluation/fall-rule-threshold-sweep.csv\` from outer-fold out-of-fold
scores. It is diagnostic; select final thresholds with a separate participant-level
validation set. SisFall falls were safely simulated during collection, not observed
unintentional falls in the wild.
`;
  fs.mkdirSync(path.dirname(REPORT_PATH), { recursive: true });
  fs.writeFileSync(REPORT_PATH, report, 'utf8');
}

function main() {
  if (!fs.existsSync(DATA_CSV)) {
    if (PREPARED_CSV) {
      throw new Error(`Prepared SisFall feature CSV not found: ${DATA_CSV}`);
    }
    if (!fs.existsSync(RAW)) {
      throw new Error(
        `SisFall source data not found. Add raw recordings under ${RAW} or set SISFALL_FEATURE_CSV to a prepared feature CSV.`,
      );
    }
    convertIfPresent();
  }

  let source = fs.readFileSync(DATA_CSV, 'utf8');
  if (source.includes('# SYNTHETIC')) {
    if (!PREPARED_CSV && fs.existsSync(RAW)) {
      convertIfPresent();
      source = fs.readFileSync(DATA_CSV, 'utf8');
    }
    if (source.includes('# SYNTHETIC')) {
      throw new Error(`Refusing to train the SisFall model from synthetic data: ${DATA_CSV}`);
    }
  }
  const rows = parseCsv(source);
  if (rows.length === 0) throw new Error(`No valid labeled feature rows found in ${DATA_CSV}`);
  if (rows.some((row) => !row.subjectId || !row.recordingId)) {
      throw new Error('SisFall rows must include subject_id and recording_id columns. Regenerate with convert_sisfall.js or provide a 17-column grouped feature CSV.');
  }

  const model = trainFromRows(rows);
  model.datasetKind = 'sisfall-public-simulated-falls';
  fs.writeFileSync(MODEL_PATH, JSON.stringify(model), 'utf8');

  fs.mkdirSync(path.dirname(SWEEP_PATH), { recursive: true });
  fs.writeFileSync(SWEEP_PATH, csv(model.thresholdSweep), 'utf8');
  writeReport(model, rows.length);
  process.stdout.write(`Trained SisFall model from ${rows.length} rows; threshold sweep: ${SWEEP_PATH}\n`);
}

try {
  main();
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
}
